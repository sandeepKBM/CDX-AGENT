"""`cdx-agent --teardown`: generate (never run) a stop script for a tmux-hosted service from a JSON spec.

    python -m cdx_agent.teardown SPEC.json [--out SCRIPT.sh]

Spec keys: name, tmux_session, groups (list of lists of tmux window names, stopped group by group), log (JSONL path);
optional expect ({window: substring its start command must contain}), busy_ports, keep_listening, after_cmd.
The script is a dry run unless CONFIRM=1: identity checks, port checks, then ``tmux kill-window`` per window (never
kill-session) with a JSONL event log. Default output: stop_<name>.sh beside the spec.

Window names are shell-quoted one by one (spaces are fine) and the script reads ``tmux list-windows -F`` output line by
line, so no name is ever word-split. A tmux session that does not exist is reported as "missing" (not "gone"); a window
missing from an existing session is "gone (already stopped)".
"""
from __future__ import annotations

import json
import os
import re
import shlex
import stat
import sys
from typing import Optional, Sequence

USAGE = "usage: cdx-agent --teardown SPEC.json [--out SCRIPT.sh]"

TEMPLATE = r'''#!/usr/bin/env bash
# Generated by cdx-agent --teardown from __SPEC__ . DRY RUN by default.
#   bash __BASE__            # checks only
#   CONFIRM=1 bash __BASE__  # kills windows group by group (tmux kill-window only, never kill-session)
set -uo pipefail
NAME=__NAME__; S=__SESS__; LOG=__LOG__
__GARR__
PORTS=(__PORTS__); KEEP=(__KEEP__)
declare -A EXP
__EXP__
AFTER=__AFTER__
mkdir -p "$(dirname "$LOG")"
ev() { python3 -c 'import json, sys, datetime; print(json.dumps({"t": datetime.datetime.now().astimezone().isoformat(timespec="seconds"), "kind": sys.argv[1], "text": sys.argv[2]}))' "$1" "$2" >> "$LOG"; }
fail=0; ok() { echo "  ok   $*"; }; bad() { echo "  FAIL $*"; fail=1; }
nconn() { ss -tnH state established "( dport = :$1 )" 2>/dev/null | wc -l; }
have_session=0
tmux has-session -t "=$S" 2>/dev/null && have_session=1
declare -A WIN_CMD
if [ "$have_session" = 1 ]; then
  while IFS=$'\t' read -r wname wcmd; do
    [ -n "$wname" ] && WIN_CMD["$wname"]="$wcmd"
  done < <(tmux list-windows -t "=$S" -F '#{window_name}'$'\t''#{pane_start_command}' 2>/dev/null)
fi
echo "== identity: each window runs what we expect"
if [ "$have_session" = 0 ]; then echo "  missing tmux session $S (no windows to check)"; fi
for ((i = 0; i < NGRP; i++)); do
  declare -n grp="GRP$i"
  for w in "${grp[@]}"; do
    [ "$have_session" = 1 ] || continue
    if [ -z "${WIN_CMD[$w]+x}" ]; then echo "  gone $w (already stopped)"; continue; fi
    sc="${WIN_CMD[$w]}"
    if [ -n "${EXP[$w]:-}" ]; then
      grep -qF -- "${EXP[$w]}" <<< "$sc" && ok "$w" || bad "$w start command does not contain '${EXP[$w]}'"
    else ok "$w (no expect)"; fi
  done
  unset -n grp
done
echo "== must keep listening"
for p in "${KEEP[@]}"; do ss -ltn | awk '{print $4}' | grep -q ":$p\$" && ok ":$p listening" || bad ":$p not listening"; done
echo "== no connection in flight"
for p in "${PORTS[@]}"; do
  n=$(nconn "$p"); [ "$n" -eq 0 ] && ok "no open conn to :$p" || bad "$n open conn(s) to :$p (episode in flight?)"
done
[ $fail = 0 ] || { echo "ABORT: checks failed; nothing stopped"; exit 1; }
if [ "${CONFIRM:-0}" != 1 ]; then echo "dry run OK (CONFIRM=1 to stop: __GROUPS_DESC__)"; exit 0; fi
ev START "stop $NAME"
first=1
for ((i = 0; i < NGRP; i++)); do
  declare -n grp="GRP$i"
  for w in "${grp[@]}"; do tmux kill-window -t "$S:=$w" 2>/dev/null && ev KILL "$w"; done
  unset -n grp
  sleep 2
  if [ $first = 1 ]; then
    first=0
    for p in "${PORTS[@]}"; do
      n=$(nconn "$p")
      [ "$n" -eq 0 ] || { ev ABORT "open conn :$p after first group"; echo "ABORT: conn on :$p appeared; first group stopped, rest still up"; exit 1; }
    done
  fi
done
[ -n "$AFTER" ] && { bash -c "$AFTER" && ev AFTER "ran after_cmd" || ev AFTER "after_cmd failed"; }
ev DONE "stopped $NAME"
echo "stopped $NAME. Check ports and public endpoints."
'''


class SpecError(Exception):
    pass


def _require(spec: dict, key: str, kind: type):
    if key not in spec:
        raise SpecError(f"teardown: spec is missing {key!r}")
    if not isinstance(spec[key], kind):
        raise SpecError(f"teardown: spec {key!r} must be a {kind.__name__}")
    return spec[key]


def render_script(spec: dict, spec_path: str, out_path: str) -> str:
    name = _require(spec, "name", str)
    sess = _require(spec, "tmux_session", str)
    groups = _require(spec, "groups", list)
    log = _require(spec, "log", str)
    for g in groups:
        if not isinstance(g, list) or not all(isinstance(w, str) for w in g):
            raise SpecError("teardown: spec 'groups' must be a list of lists of window-name strings")
    expect = spec.get("expect", {})
    if not isinstance(expect, dict):
        raise SpecError("teardown: spec 'expect' must be an object")
    busy = [str(p) for p in spec.get("busy_ports", [])]
    keep = [str(p) for p in spec.get("keep_listening", [])]
    after = str(spec.get("after_cmd", ""))
    q = shlex.quote
    wins = [w for g in groups for w in g]
    garr = "\n".join(f"GRP{i}=({' '.join(q(w) for w in g)})" for i, g in enumerate(groups))
    garr = (garr + "\n" if garr else "") + f"NGRP={len(groups)}"
    exp_lines = "\n".join(f"EXP[{q(w)}]={q(str(expect[w]))}" for w in wins if w in expect)
    desc = "; ".join(" ".join(g) for g in groups)
    rep = {"__SPEC__": spec_path, "__BASE__": os.path.basename(out_path), "__NAME__": q(name), "__SESS__": q(sess),
           "__LOG__": q(log), "__GARR__": garr, "__PORTS__": " ".join(q(p) for p in busy),
           "__KEEP__": " ".join(q(p) for p in keep), "__EXP__": exp_lines, "__AFTER__": q(after),
           "__GROUPS_DESC__": re.sub(r"[\"$`\\]", "", desc)}
    # single pass, so a placeholder-looking window name is not expanded a second time
    pattern = re.compile("|".join(re.escape(k) for k in sorted(rep, key=len, reverse=True)))
    return pattern.sub(lambda m: rep[m.group(0)], TEMPLATE)


def default_out(spec_path: str, name: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9._-]", "_", name) or "service"
    return os.path.join(os.path.dirname(os.path.abspath(spec_path)), f"stop_{safe}.sh")


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args in (["--help"], ["-h"]):
        print(USAGE)
        return 0
    spec_path = args[0] if args else ""
    if not spec_path or spec_path.startswith("--") or not os.path.isfile(spec_path):
        print(USAGE, file=sys.stderr)
        return 2
    out = ""
    i = 1
    while i < len(args):
        if args[i] == "--out":
            if i + 1 >= len(args):
                print("teardown: --out needs a path", file=sys.stderr)
                return 2
            out = args[i + 1]
            i += 2
        else:
            print(f"teardown: unknown argument {args[i]}", file=sys.stderr)
            return 2
    try:
        with open(spec_path) as f:
            spec = json.load(f)
        if not isinstance(spec, dict):
            raise SpecError("teardown: spec must be a JSON object")
        if not out:
            out = default_out(spec_path, _require(spec, "name", str))
        script = render_script(spec, spec_path, out)
    except json.JSONDecodeError as exc:
        print(f"teardown: {spec_path} is not valid JSON: {exc}", file=sys.stderr)
        return 2
    except SpecError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    with open(out, "w") as f:
        f.write(script)
    os.chmod(out, os.stat(out).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
